# ========== 生成大纲 ==========

def generate_outline():
    lines = []
    lines.append("# 365天眼镜门店员工晋级培训大纲\n")
    lines.append("> 本大纲为眼镜连锁门店在职员工365天晋级培训计划，分为四大模块，每天一个主题。\n")
    lines.append("> 生成时间：2026年5月\n")
    lines.append("\n---\n")
    
    total_days = 0
    for mod_idx, module in enumerate(MODULES):
        mod_name = module["name"]
        mod_start, mod_end = module["days"]
        mod_days = mod_end - mod_start + 1
        total_days += mod_days
        
        lines.append(f"\n## 模块{mod_idx+1}：{mod_name}（第{mod_start}-{mod_end}天，共{mod_days}天）\n")
        
        day_counter = mod_start
        for week in module["weeks"]:
            lines.append(f"\n### {week['week']}：{week['theme']}\n")
            lines.append("| 天数 | 主题 |")
            lines.append("|------|------|")
            
            for day_topic in week["days"]:
                if day_counter <= mod_end:
                    lines.append(f"| 第{day_counter}天 | {day_topic} |")
                    day_counter += 1
            
            lines.append("")  # 空行分隔
        
        # 如果该模块的days数量与实际生成的不一致，补充或截断
        # （由于每周天数可能不精确，这里做容错处理）
    
    lines.append(f"\n---\n")
    lines.append(f"\n**总计：{total_days}天**\n")
    lines.append("\n> 说明：本大纲为草案，请根据实际培训需求调整主题顺序和具体内容。\n")
    
    return "\n".join(lines)

