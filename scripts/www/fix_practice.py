FOOTER_BLOCK = '''    <!-- 底部技术支持署名 -->
    <div class="footer-support">
        技术支持：闫胜君视光工作室
    </div>
'''

for fname, d in DATA.items():
    if not os.path.exists(fname):
        print('MISSING', fname); continue
    bak = fname + '.bak_practice'
    if not os.path.exists(bak):
        shutil.copy2(fname, bak)
    s = open(fname, encoding='utf-8').read()

    # 1. 填充选项
    it = iter(d['options'])
    def fill(m):
        opts = next(it)
        lines = ',\n'.join('                    { text: \'%s\' }' % o.replace('\\', '') for o in opts)
        return 'options: [\n%s\n                ]' % lines
    s2, n = re.subn(r'options: \[\s*\]', fill, s)
    if n != 3:
        print('WARN', fname, 'options replaced:', n)

    # 2. 题号去重  "1. 1. " -> "1. "
    s2 = re.sub(r'(question-text">)(\d+)\. \2\. ', lambda m: m.group(1) + m.group(2) + '. ', s2)

    # 3. 插入问答题 + 提交区 + 得分显示
    ph = '            <!-- 问答题部分需要手动调整 -->'
    if ph in s2:
        s2 = s2.replace(ph, SUBMIT_BLOCK.format(q=d['essay_q'], a=d['essay_a']).rstrip('\n'))
    else:
        print('WARN', fname, '占位注释未找到')

    # 4. 页脚移到 </body> 之前
    if s2.rfind('footer-support') > s2.rfind('</html>'):
        s2 = re.sub(r'</html>\s*<div class="footer-support">\s*技术支持：闫胜君视光工作室\s*</div>\s*$', '</html>\n', s2)
        # 去掉 </body> 前残留的空注释行，避免重复
        s2 = re.sub(r'[ \t]*<!-- 底部技术支持署名 -->[ \t]*\n', '', s2)
        s2 = re.sub(r'\n\s*(?=</body>)', '\n', s2)
        s2 = s2.replace('</body>', FOOTER_BLOCK + '</body>', 1)

    open(fname, 'w', encoding='utf-8', newline='\n').write(s2)
    print('OK', fname, len(s), '->', len(s2))
